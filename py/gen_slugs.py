#!/usr/bin/env python3
"""Write the localized-slug map everywhere it is needed:
  1. tokens.js  - window.UX_SLUGS between // BEGIN SLUGS / // END SLUGS
  2. .htaccess  - 301s from /fr/<en>.html to /fr/<local>.html, and internal
                  rewrites from /fr/<local>.html to the English page shell
  3. *.html     - hreflang alternates point at the localized addresses
Run after changing a title translation, then gen_share.py and gen_sitemap.py.
"""
import glob
import json
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from slugs import SITE, LANGS, TRANSLATED, build

BASE = 'https://www.ux-guidelines.com/'


def main():
    slugs = build()
    # 1. tokens.js
    t = open(f'{SITE}/tokens.js').read()
    block = '// BEGIN SLUGS\nwindow.UX_SLUGS = ' + json.dumps({l: {k: v for k, v in slugs[l].items() if v != k} for l in TRANSLATED}, ensure_ascii=False, separators=(',', ':')) + ';\n// END SLUGS\n'
    if '// BEGIN SLUGS' in t:
        t = re.sub(r'// BEGIN SLUGS\n.*?// END SLUGS\n', block, t, flags=re.DOTALL)
    else:
        t = block + t
    open(f'{SITE}/tokens.js', 'w').write(t)
    # 2. .htaccess
    h = open(f'{SITE}/.htaccess').read()
    redirects, rewrites = [], []
    for lang in TRANSLATED:
        for en, local in sorted(slugs[lang].items()):
            if local == en:
                continue
            redirects.append(f'RewriteRule ^{lang}/{re.escape(en)}\\.html$ /{lang}/{local}.html [R=301,L]')
            rewrites.append(f'RewriteRule ^{lang}/{re.escape(local)}\\.html$ {en}.html [L]')
    rblock = '# BEGIN localized slug redirects (generated by py/gen_slugs.py)\n' + '\n'.join(redirects) + '\n# END localized slug redirects\n'
    wblock = '# BEGIN localized slug rewrites (generated by py/gen_slugs.py)\n' + '\n'.join(rewrites) + '\n# END localized slug rewrites\n'
    if '# BEGIN localized slug redirects' in h:
        h = re.sub(r'# BEGIN localized slug redirects.*?# END localized slug redirects\n', rblock, h, flags=re.DOTALL)
        h = re.sub(r'# BEGIN localized slug rewrites.*?# END localized slug rewrites\n', wblock, h, flags=re.DOTALL)
    else:
        h = h.replace('# Social scrapers do not run JS', rblock + '\n# Social scrapers do not run JS', 1)
        h = h.replace('# Language-prefixed URLs serve the same page shell', wblock + '\n# Language-prefixed URLs serve the same page shell', 1)
    assert h.count('# BEGIN localized slug') == 2
    open(f'{SITE}/.htaccess', 'w').write(h)
    # 3. hreflang alternates in every public page
    n = 0
    for f in glob.glob(f'{SITE}/*.html'):
        base = os.path.basename(f)[:-5]
        if base in ('design-system', 'roadmap'):
            continue
        s = open(f).read()
        orig = s
        for lang in TRANSLATED:
            page = '' if base == 'index' else slugs[lang].get(base, base) + '.html'
            s = re.sub(r'(hreflang="%s" href="%s%s/)[^"]*"' % (lang, re.escape(BASE), lang), r'\g<1>' + page + '"', s)
        if s != orig:
            open(f, 'w').write(s)
            n += 1
    print(f'slugs: {sum(1 for l in TRANSLATED for k, v in slugs[l].items() if v != k)} localized across {len(TRANSLATED)} languages; '
          f'{len(redirects)} redirects, {len(rewrites)} rewrites; hreflang updated on {n} pages')


if __name__ == '__main__':
    main()
